import re
import struct
import unicodedata
from pathlib import Path

from c2s import messages

HEADER = "disc.h"
MONSTER_ID = 0
MONSTER_NAME = (4, 36)
MONSTER_MODEL = (36, 52)
MONSTER_SCRIPT = (52, 68)


def text_at(record, span):
    return record[span[0]:span[1]].split(b"\x00")[0].decode("cp932", "replace")


def file_offset(elf, address):
    table, count = struct.unpack_from("<I", elf, 28)[0], struct.unpack_from("<H", elf, 44)[0]
    for number in range(count):
        kind, offset, virtual, _, size = struct.unpack_from("<5I", elf, table + 32 * number)
        if kind == 1 and virtual <= address < virtual + size:
            return offset + address - virtual
    return None


def monster_table(elf, layout):
    start = file_offset(elf, layout["address"])
    rows = {}
    if start is None:
        return rows
    position = start
    while position + layout["record_size"] <= len(elf):
        record = elf[position:position + layout["record_size"]]
        model = text_at(record, MONSTER_MODEL)
        if not model:
            break
        rows.setdefault(struct.unpack_from("<h", record, MONSTER_ID)[0],
                        {"name": text_at(record, MONSTER_NAME), "model": model, "script": text_at(record, MONSTER_SCRIPT)})
        position += layout["record_size"]
    return rows


def executable(root, defs):
    name = defs.get("executable", {}).get("name")
    path = Path(root) / name if name else None
    return path.read_bytes() if path is not None and path.is_file() else None


def tables(root, defs):
    code = defs["text"].get("languages", {}).get(defs["language"])
    found = messages.disc_names(root, code) if code is not None else {}
    elf = executable(root, defs)
    layout = defs.get("executable", {}).get("monster_table")
    monsters = monster_table(elf, layout) if elf is not None and layout else {}
    found["monster_kind"] = {number: row["name"] for number, row in monsters.items() if row["name"]}
    found["monster_kind_notes"] = {number: monster_note(row) for number, row in monsters.items() if row["name"]}
    found.setdefault("chara_pack", {})
    for row in monsters.values():
        if row["name"]:
            found["chara_pack"].setdefault(row["model"], row["name"])
    return found


# Where a monster kind's files are: its model pack and the AI script it runs, both under
# dungeon/monster/. Kinds can share an AI script, and an event-only kind can have its own.
def monster_note(row):
    return "model %s, AI %s" % (row["model"], row["script"] or row["model"])


def identifier(text, prefix):
    plain = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    words = re.findall(r"[A-Za-z0-9]+", plain.replace("'", ""))
    return "_".join([prefix] + [word.upper() for word in words]) if words else None


def enum_lines(name, prefix, values, taken, notes=None):
    lines = ["enum %s {" % name]
    for number in sorted(values):
        constant = identifier(values[number], prefix)
        if constant is None:
            continue
        if constant in taken:
            constant = "%s_%d" % (constant, number)
        if constant in taken:
            continue
        taken.add(constant)
        note = (notes or {}).get(number)
        lines.append("    %s = %d,%s" % (constant, number, "  // " + note if note else ""))
    return lines + ["};", ""]


ENUMS = (("monster_kind", "MONSTER", "Monster kinds, from the game executable's monster table."),
         ("item_id", "ITEM", "Items, from the item names in menu/cfg7/comdatmes<language>.cfg."),
         ("npc_id", "NPC", "Characters, from npc<language>.cfg."))


def header(found, taken):
    lines = ["// Names read from the disc this source was decompiled from. Generated by cli.py; not part of",
             "// the repository, since the names are the game's own text.", "#ifndef DISC_H", "#define DISC_H", ""]
    used = set(taken)
    present = False
    for name, prefix, doc in ENUMS:
        if found.get(name):
            lines += ["// " + doc] + enum_lines(name, prefix, found[name], used, found.get(name + "_notes"))
            present = True
    return "\n".join(lines + ["#endif", ""]) if present else None


CONSTANT = re.compile(r"^\s*(?:#define\s+)?([A-Z][A-Z0-9_]*)\b", re.M)


def with_header(root, defs, headers):
    taken = {name for text in headers.values() for name in CONSTANT.findall(text)}
    text = header(tables(root, defs), taken)
    if text is None:
        return defs, headers, None
    include = defs["include"] + ([HEADER] if HEADER not in defs["include"] else [])
    return dict(defs, include=include), dict(headers, **{HEADER: text}), text
