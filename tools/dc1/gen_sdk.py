"""Writes a Dark Cloud 1 SDK (sdk-dc1/) from the native tables `dc2tk natives <Chronicle checkout>` wrote.

Each native gets a declaration named after its original name (lower case, the leading _ dropped)
with one parameter per stack accessor its body calls, in order. Natives whose accessors include an
out slot or `any` are declared with VM_ARGS, since their result types are not known yet.
usage: python tools/dc1/gen_sdk.py definitions/dc1/natives sdk-dc1
"""
import json, os, shutil, sys

KIND = {"int": "int", "float": "float", "string": "string", "any": "any", "vector": "any",
        "out": "any *", "out_vector": "any *"}
HEADER = {"monster": "Natives for DC1 monster AI scripts (dun/monstor), runscript_opcodes.cpp ext_func_info.",
          "event": "Natives for DC1 town/Georama event scripts (gedit, dun/script), editloop3.cpp ext_func_info."}


def declaration(native):
    accessors = native["accessors"] or []
    params, outs = [], 0
    for i, kind in enumerate(accessors):
        if kind.startswith("out"):
            params.append(f"{KIND[kind]}out{outs}")
            outs += 1
        else:
            params.append(f"{KIND[kind]} a{i}")
    name = native["name"].lstrip("_").lower()
    loose = native["accessors"] is None or any(k in ("out", "out_vector", "any", "vector") for k in accessors)
    args = ", ".join(params) if params else ("" if loose else "void")
    form = f"VM_ARGS({args})" if loose else f"({args})"
    return f"// Original name: {native['name']}.\nextern void {name} {form} NATIVE({native['no']});\n"


def main(natives_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    here = os.path.dirname(os.path.abspath(__file__))
    for common in ("dc2tk.h", "float.h", "limits.h", "stdarg.h", "stddef.h"):
        shutil.copy(os.path.join(here, "..", "..", "sdk", common), os.path.join(out_dir, common))
    for name in sorted(os.listdir(natives_dir)):
        table = json.load(open(os.path.join(natives_dir, name), encoding="utf-8"))
        guard = f"DC1TK_{table['table'].upper()}_H"
        body = [f"// dc1tk SDK (generated by tools/dc1/gen_sdk.py, do not edit). {HEADER[table['table']]}\n\n",
                f"#ifndef {guard}\n#define {guard}\n\n#include <dc2tk.h>\n#pragma natives {table['table']}\n\n"]
        body += [declaration(n) + "\n" for n in table["natives"]]
        body.append(f"#endif\n")
        open(os.path.join(out_dir, f"{table['table']}.h"), "w", encoding="utf-8", newline="\n").write("".join(body))
        print(f"{table['table']}.h: {len(table['natives'])} natives")


if __name__ == "__main__":
    main(*sys.argv[1:3])
